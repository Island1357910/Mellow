/** @param {number} completedUpTo mainStoryCompletedUpTo */
export function getMainStoryChapterIndexForDisplay(state) {
  const up = state.mainStoryCompletedUpTo ?? -1;
  const next = up + 1;
  if (next >= mainStoryChapters.length) return mainStoryChapters.length - 1;
  return next;
}

export function isMainStoryChapterUnlocked(chapterIndex, state) {
  const ch = mainStoryChapters[chapterIndex];
  if (!ch) return false;
  if (!ch.quest.done(state)) return false;
  if (chapterIndex === 0) return true;
  const up = state.mainStoryCompletedUpTo ?? -1;
  return up >= chapterIndex - 1;
}

export function computeEndingIdFromChoices(choices) {
  const c5 = choices?.branch_ch5;
  if (c5 === 'B') return 'forgotten';
  return 'true_end';
}
