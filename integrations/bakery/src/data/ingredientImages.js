/**
 * 用 AI 原料 sku 名称做字符码求和哈希，从该类别的全量图片列表中确定性地选一张。
 * 相同 sku → 相同图片；不同 sku → 大概率不同图片。
 */
export function getRandomImageUrlForCategory(category, skuName) {
  const skus = CATEGORY_IMAGE_SKUS[category];
  if (!skus || skus.length === 0) return getPresetImageUrlForCategory(category);
  const hash = String(skuName || '').split('').reduce((acc, ch) => acc + ch.charCodeAt(0), 0);
  const picked = skus[hash % skus.length];
  return getIngredientImageUrl(picked) || getPresetImageUrlForCategory(category);
}

export function getPresetImageUrlForCategory(category) {
  const sku = category && CATEGORY_PRESET_THUMB_SKU[category];
  return sku ? getIngredientImageUrl(sku) : null;
}

/**
 * 将玩家/AI 可能输入的原料简称解析为游戏内 sku，便于 IngredientThumb 显示图
 */
export function resolveIngredientSkuForThumb(raw) {
  if (raw == null || raw === '') return null;
  const s = String(raw).trim();
  if (getIngredientImageUrl(s)) return s;
  const fromLine = ingredientNameFromLine(s);
  if (fromLine && getIngredientImageUrl(fromLine)) return fromLine;
  const keys = Object.keys(INGREDIENT_IMAGE_URL_BY_SKU);
  for (const k of keys) {
    if (!k) continue;
    if (k.includes(s) || s.includes(k)) return k;
  }
  return s;
}
