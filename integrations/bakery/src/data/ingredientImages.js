/** 从「原料行」文案拆出名称（与 getIngredientCapsuleCategory 一致） */
export function ingredientNameFromLine(str) {
  return String(str)
    .replace(/\s+\d+(\.\d+)?\s*克?$/, '')
    .replace(/\s+\d+(\.\d+)?\s*g$/i, '')
    .trim();
}

export function getIngredientImageUrl(nameOrSku) {
  if (!nameOrSku) return null;
  const direct = INGREDIENT_IMAGE_URL_BY_SKU[nameOrSku];
  if (direct) return direct;
  const fromLine = ingredientNameFromLine(nameOrSku);
  return INGREDIENT_IMAGE_URL_BY_SKU[fromLine] || null;
}

