const HUMAN_ANCHORS: AnchorProfile[] = RAW.map((r, i) => {
  const visual = getAnchorVisual(i);
  return {
    id: `anchor_${i + 1}`,
    ...r,
    isHuman: true,
    gradient: GRADIENTS[i % GRADIENTS.length],
    avatarLetter: r.stageName.charAt(0),
    portraitUrl: visual?.portraitUrl,
    hairColor: visual?.hairColor,
  };
});

const NON_HUMAN_ANCHORS: AnchorProfile[] = NON_HUMAN_RAW.map((r, i) => {
  const visual = getNonHumanVisual(r.realNameZh);
  const { realNameZh: _zh, ...rest } = r;
  return {
    id: `anchor_${HUMAN_ANCHORS.length + i + 1}`,
    ...rest,
    isHuman: false,
    gradient: GRADIENTS[(HUMAN_ANCHORS.length + i) % GRADIENTS.length],
    avatarLetter: r.stageName.charAt(0),
    portraitUrl: visual?.portraitUrl,
    hairColor: visual?.hairColor,
  };
});

export const ANCHORS: AnchorProfile[] = [...HUMAN_ANCHORS, ...NON_HUMAN_ANCHORS];

export const ANCHOR_GRADIENTS = GRADIENTS;

/** 内置 + 玩家自定义主播 */
export function getAllAnchors(): AnchorProfile[] {
  return [...ANCHORS, ...getCustomAnchorsRegistry()];
}

export function getAnchorById(id: string): AnchorProfile | undefined {
  return ANCHORS.find((a) => a.id === id) ?? getCustomAnchorsRegistry().find((a) => a.id === id);
}

export function getAnchorByStageName(name: string): AnchorProfile | undefined {
  return (
    ANCHORS.find((a) => a.stageName === name) ??
    getCustomAnchorsRegistry().find((a) => a.stageName === name)
  );
}

export function isNonHumanAnchor(anchor: AnchorProfile): boolean {
  return anchor.isHuman === false;
}

export function isCustomAnchor(anchor: AnchorProfile): boolean {
  return anchor.isCustom === true;
}
