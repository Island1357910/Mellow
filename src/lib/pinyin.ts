/** 昵称或备注的拼音首字母。字母开头直接用，对不上的归到 #。 */
export function nameLetter(name: string): string {
  const char = [...name.trim()][0] ?? ''
  if (!char) return '#'
  if (/[A-Za-z]/.test(char)) return char.toUpperCase()
  if (/[0-9]/.test(char)) return '#'
  return LETTERS.get(char) ?? '#'
}
